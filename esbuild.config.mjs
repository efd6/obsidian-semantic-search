import esbuild from "esbuild";
import process from "process";
import builtins from "builtin-modules";
import { cpSync, existsSync, mkdirSync } from "fs";
import { join, dirname } from "path";
import { fileURLToPath } from "url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = (process.argv[2] === 'production');
const buildMode = process.argv[2]; // 'production', 'development', or undefined (watch mode)




// Copy additional plugin files
const copyPluginFiles = () => {
	const files = [
		{ src: 'manifest.json', dest: 'build/plugin/manifest.json' },
		{ src: 'styles.css', dest: 'build/plugin/styles.css' }
	];

	files.forEach(({ src, dest }) => {
		const srcPath = join(__dirname, src);
		const destPath = join(__dirname, dest);

		if (existsSync(srcPath)) {
			try {
				cpSync(srcPath, destPath);
				console.log(`✓ Copied ${src} to ${dest}`);
			} catch (error) {
				console.warn(`⚠ Could not copy ${src}:`, error.message);
			}
		}
	});
};

// Native module stub plugin
const stubPlugin = {
	name: 'stub-plugin',
	setup(build) {
		// TensorFlow.js works natively in browser environments
		// No additional stubs needed

		// Removed stub mappings - TensorFlow.js has no filesystem dependencies
	}
};

// Worker bundling plugin
const workerPlugin = {
	name: 'worker-plugin',
	setup(build) {
		build.onResolve({ filter: /\.worker\.(ts|js)$/ }, (args) => {
			return { path: args.path, namespace: 'worker' };
		});

		build.onLoad({ filter: /.*/, namespace: 'worker' }, async (args) => {
			const workerResult = await esbuild.build({
				entryPoints: [args.path],
				bundle: true,
				format: 'iife',
				target: 'es2020',
				write: false,
				minify: prod,
				define: {
					'process.env.NODE_ENV': JSON.stringify(prod ? 'production' : 'development')
				}
			});

			const workerCode = workerResult.outputFiles[0].text;
			return {
				contents: `export default ${JSON.stringify(workerCode)};`,
				loader: 'js'
			};
		});
	}
};

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ['main.ts'],
	bundle: true,
	// No aliases needed for TensorFlow.js
	external: [
		'obsidian',
		'electron',
		'@codemirror/autocomplete',
		'@codemirror/collab',
		'@codemirror/commands',
		'@codemirror/language',
		'@codemirror/lint',
		'@codemirror/search',
		'@codemirror/state',
		'@codemirror/view',
		'@lezer/common',
		'@lezer/highlight',
		'@lezer/lr',
		...builtins
	],
	format: 'cjs',
	platform: 'browser',
	target: 'es2020',
	logLevel: "info",
	sourcemap: prod ? false : 'inline',
	treeShaking: true,
	minify: prod,
	outfile: 'build/plugin/main.js',
	plugins: [stubPlugin, workerPlugin],
	define: {
		'process.env.NODE_ENV': JSON.stringify(prod ? 'production' : 'development'),
		'process.release.name': JSON.stringify('browser'),
		'global': 'globalThis'
	},
	resolveExtensions: ['.ts', '.js'],
	loader: {
		'.wasm': 'binary',
		'.bin': 'binary'
	}
});

if (buildMode === 'production' || buildMode === 'development') {
	// Build once and exit for both production and development modes
	copyPluginFiles();
	await context.rebuild();
	if (prod) {
		console.log('✓ Production build complete in build/plugin/');
	} else {
		console.log('✓ Development build complete in build/plugin/ (unminified)');
	}
	process.exit(0);
} else {
	// Watch mode when no build mode is specified
	await context.watch();
	console.log('👀 Watching for changes...');
}
